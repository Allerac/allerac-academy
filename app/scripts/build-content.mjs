// Build step: parses content/<lang>/ and tutor/ into src/generated/content.ts.
// Wrangler runs this automatically before `wrangler dev` and `wrangler deploy`
// (see "build" in wrangler.jsonc), so editing Markdown needs no code changes.

import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildCourse, SECTION_LABELS } from "./lib/parse-content.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..", "..");
const contentRoot = join(repoRoot, "content");
const outDir = join(here, "..", "src", "generated");

const courses = {};
for (const lang of readdirSync(contentRoot)) {
  if (!statSync(join(contentRoot, lang)).isDirectory()) continue;
  if (!SECTION_LABELS[lang]) {
    console.warn(`[content] skipping "${lang}": no section labels defined`);
    continue;
  }
  const course = buildCourse(contentRoot, lang);
  if (course) courses[lang] = course;
}
if (!courses.pt) throw new Error("[content] content/pt/course.md is required");

const tutorSystemPrompt = readFileSync(join(repoRoot, "tutor", "system-prompt.md"), "utf8");

mkdirSync(outDir, { recursive: true });
const banner = "// GENERATED by scripts/build-content.mjs. Do not edit; edit content/ or tutor/ instead.\n";
writeFileSync(
  join(outDir, "content.ts"),
  banner +
    `import type { CourseBundle } from "../types";\n` +
    `export const courses: Record<string, CourseBundle> = ${JSON.stringify(courses)};\n` +
    `export const tutorSystemPrompt: string = ${JSON.stringify(tutorSystemPrompt)};\n`,
);

for (const [lang, c] of Object.entries(courses)) {
  const lessonCount = Object.keys(c.lessons).length;
  console.log(`[content] ${lang}: ${c.modules.length} modules in map, ${lessonCount} lessons`);
}
